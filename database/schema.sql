-- =============================================================================
--  Andon Monitoring System & OEE
--  PostgreSQL schema  (single database shared by ALL modules)
--
--  Modules that read/write these tables:
--    masterdata  -> roles, users, shifts, items, machines, abnormalities,
--                   defects, production_setups
--    workorder   -> work_orders, work_order_items
--    production  -> production_logs, downtime_logs
--    oee         -> oee_records (read + write, computed from logs)
--    analytics   -> reads production_logs / downtime_logs / oee_records
--
--  Conventions
--    * Primary keys are UUIDs generated by gen_random_uuid() (built into
--      PostgreSQL 13+, no extension required).
--    * Timestamps are TIMESTAMPTZ and always stored in UTC.
--    * Enumerations are TEXT + CHECK constraints instead of native ENUM types so
--      that values can be extended without ALTER TYPE migrations.
--      The values MUST stay in sync with `shared/src/constants/enums.ts`.
--    * Money/quantity are integers, ratios are NUMERIC(7,4) in range 0..1.
--
--  Apply with:  npm run db:schema     (see database/README.md)
-- =============================================================================

BEGIN;

-- -----------------------------------------------------------------------------
-- Reusable trigger: keep updated_at fresh
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- =============================================================================
--  MODULE 1 : MASTERDATA
-- =============================================================================

-- -----------------------------------------------------------------------------
--  roles — permission source. `base_role` maps a custom role onto one of the
--  three system roles so the permission matrix in shared/ stays authoritative.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS roles (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  code        TEXT NOT NULL,
  name        TEXT NOT NULL,
  description TEXT,
  base_role   TEXT CHECK (base_role IN ('ADMIN', 'SUPERVISOR', 'OPERATOR')),
  is_system   BOOLEAN NOT NULL DEFAULT FALSE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT roles_code_unique UNIQUE (code),
  CONSTRAINT roles_code_not_blank CHECK (length(btrim(code)) > 0),
  CONSTRAINT roles_name_not_blank CHECK (length(btrim(name)) > 0)
);

COMMENT ON TABLE roles IS 'Role definitions. code must be unique; base_role drives the permission matrix.';

-- -----------------------------------------------------------------------------
--  users — password_hash is a bcrypt hash; never returned by the API.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
  id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  email         TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  full_name     TEXT NOT NULL,
  role_id       UUID NOT NULL REFERENCES roles (id) ON DELETE RESTRICT,
  is_active     BOOLEAN NOT NULL DEFAULT TRUE,
  last_login_at TIMESTAMPTZ,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT users_email_unique UNIQUE (email),
  CONSTRAINT users_email_lowercase CHECK (email = lower(btrim(email))),
  CONSTRAINT users_email_format CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  CONSTRAINT users_full_name_not_blank CHECK (length(btrim(full_name)) > 0),
  CONSTRAINT users_password_hash_not_blank CHECK (length(password_hash) > 0)
);

CREATE INDEX IF NOT EXISTS users_role_id_idx ON users (role_id);
CREATE INDEX IF NOT EXISTS users_is_active_idx ON users (is_active);

-- -----------------------------------------------------------------------------
--  shifts — planned_minutes is the planned production time used by OEE
--  Availability. It is stored explicitly so overnight shifts (22:00-06:00)
--  never depend on ambiguous time arithmetic.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS shifts (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  code            TEXT NOT NULL,
  name            TEXT NOT NULL,
  start_time      TIME NOT NULL,
  end_time        TIME NOT NULL,
  planned_minutes INTEGER NOT NULL DEFAULT 480,
  description     TEXT,
  is_active       BOOLEAN NOT NULL DEFAULT TRUE,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT shifts_code_unique UNIQUE (code),
  CONSTRAINT shifts_name_not_blank CHECK (length(btrim(name)) > 0),
  CONSTRAINT shifts_start_ne_end CHECK (start_time <> end_time),
  CONSTRAINT shifts_planned_minutes_positive CHECK (planned_minutes > 0 AND planned_minutes <= 1440)
);

-- -----------------------------------------------------------------------------
--  items — standard_cycle_time (seconds) is the ideal cycle time used by the
--  OEE Performance factor.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS items (
  id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  code                TEXT NOT NULL,
  name                TEXT NOT NULL,
  category            TEXT,
  unit                TEXT NOT NULL DEFAULT 'PCS',
  standard_cycle_time NUMERIC(10, 3) CHECK (standard_cycle_time > 0),
  description         TEXT,
  is_active           BOOLEAN NOT NULL DEFAULT TRUE,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT items_code_unique UNIQUE (code),
  CONSTRAINT items_name_not_blank CHECK (length(btrim(name)) > 0),
  CONSTRAINT items_unit_not_blank CHECK (length(btrim(unit)) > 0)
);

CREATE INDEX IF NOT EXISTS items_is_active_idx ON items (is_active);

-- -----------------------------------------------------------------------------
--  machines — `status` is a denormalised cache of the latest production event.
--  The source of truth is production_logs / downtime_logs; the production
--  service updates this column inside the same transaction as every event.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS machines (
  id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  code               TEXT NOT NULL,
  name               TEXT NOT NULL,
  area               TEXT,
  status             TEXT NOT NULL DEFAULT 'IDLE'
                     CHECK (status IN ('IDLE', 'RUNNING', 'DOWN', 'SETUP')),
  default_cycle_time NUMERIC(10, 3) CHECK (default_cycle_time > 0),
  description        TEXT,
  is_active          BOOLEAN NOT NULL DEFAULT TRUE,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT machines_code_unique UNIQUE (code),
  CONSTRAINT machines_name_not_blank CHECK (length(btrim(name)) > 0)
);

CREATE INDEX IF NOT EXISTS machines_status_idx ON machines (status);
CREATE INDEX IF NOT EXISTS machines_is_active_idx ON machines (is_active);

-- -----------------------------------------------------------------------------
--  abnormalities — is_planned = true means the downtime is planned and is
--  therefore excluded from the OEE Availability calculation.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS abnormalities (
  id                         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  code                       TEXT NOT NULL,
  name                       TEXT NOT NULL,
  category                   TEXT NOT NULL DEFAULT 'OTHER'
                             CHECK (category IN ('MECHANICAL', 'ELECTRICAL', 'MATERIAL', 'PROCESS', 'SENSOR', 'OTHER')),
  is_planned                 BOOLEAN NOT NULL DEFAULT FALSE,
  default_duration_minutes   INTEGER CHECK (default_duration_minutes > 0),
  description                TEXT,
  is_active                  BOOLEAN NOT NULL DEFAULT TRUE,
  created_at                 TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at                 TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT abnormalities_code_unique UNIQUE (code),
  CONSTRAINT abnormalities_name_not_blank CHECK (length(btrim(name)) > 0)
);

-- -----------------------------------------------------------------------------
--  defects
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS defects (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  code        TEXT NOT NULL,
  name        TEXT NOT NULL,
  defect_type TEXT,
  description TEXT,
  is_active   BOOLEAN NOT NULL DEFAULT TRUE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT defects_code_unique UNIQUE (code),
  CONSTRAINT defects_name_not_blank CHECK (length(btrim(name)) > 0)
);

CREATE INDEX IF NOT EXISTS defects_is_active_idx ON defects (is_active);

-- -----------------------------------------------------------------------------
--  production_setups — changeover masterdata (setup type + duration).
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS production_setups (
  id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  code          TEXT NOT NULL,
  name          TEXT NOT NULL,
  item_id       UUID REFERENCES items (id) ON DELETE SET NULL,
  machine_id    UUID REFERENCES machines (id) ON DELETE SET NULL,
  setup_minutes INTEGER NOT NULL DEFAULT 0,
  description   TEXT,
  is_active     BOOLEAN NOT NULL DEFAULT TRUE,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT production_setups_code_unique UNIQUE (code),
  CONSTRAINT production_setups_name_not_blank CHECK (length(btrim(name)) > 0),
  CONSTRAINT production_setups_minutes_non_negative CHECK (setup_minutes >= 0)
);

CREATE INDEX IF NOT EXISTS production_setups_item_id_idx ON production_setups (item_id);
CREATE INDEX IF NOT EXISTS production_setups_machine_id_idx ON production_setups (machine_id);

-- =============================================================================
--  MODULE 2 : WORK ORDER
-- =============================================================================

-- -----------------------------------------------------------------------------
--  work_orders
--    period_type MONTHLY  -> planning horizon is the month
--    period_type DAILY    -> planning horizon is the day
--    `item_id` is the primary item of the work order (authoritative for the
--    operator playground and the Andon board). `work_order_items` holds the
--    optional additional item lines of a multi item work order.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS work_orders (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  code            TEXT NOT NULL,
  period_type     TEXT NOT NULL CHECK (period_type IN ('MONTHLY', 'DAILY')),
  period_start    DATE NOT NULL,
  period_end      DATE NOT NULL,
  status          TEXT NOT NULL DEFAULT 'DRAFT'
                  CHECK (status IN ('DRAFT', 'PENDING_APPROVAL', 'APPROVED', 'REJECTED', 'RUNNING', 'COMPLETED', 'CANCELLED')),
  machine_id      UUID NOT NULL REFERENCES machines (id) ON DELETE RESTRICT,
  item_id         UUID NOT NULL REFERENCES items (id) ON DELETE RESTRICT,
  shift_id        UUID NOT NULL REFERENCES shifts (id) ON DELETE RESTRICT,
  target_qty      INTEGER NOT NULL CHECK (target_qty > 0),
  planned_start   TIMESTAMPTZ,
  planned_end     TIMESTAMPTZ,
  approved_by     UUID REFERENCES users (id) ON DELETE SET NULL,
  approved_at     TIMESTAMPTZ,
  approval_notes  TEXT,
  created_by      UUID REFERENCES users (id) ON DELETE SET NULL,
  notes           TEXT,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT work_orders_code_unique UNIQUE (code),
  CONSTRAINT work_orders_period_valid CHECK (period_end >= period_start),
  CONSTRAINT work_orders_planned_window_valid CHECK (planned_end IS NULL OR planned_start IS NULL OR planned_end >= planned_start)
);

CREATE INDEX IF NOT EXISTS work_orders_status_idx ON work_orders (status);
CREATE INDEX IF NOT EXISTS work_orders_period_idx ON work_orders (period_start, period_end);
CREATE INDEX IF NOT EXISTS work_orders_machine_period_idx ON work_orders (machine_id, period_start);
CREATE INDEX IF NOT EXISTS work_orders_shift_idx ON work_orders (shift_id);

-- -----------------------------------------------------------------------------
--  work_order_items — item lines of a work order
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS work_order_items (
  id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  work_order_id UUID NOT NULL REFERENCES work_orders (id) ON DELETE CASCADE,
  item_id       UUID NOT NULL REFERENCES items (id) ON DELETE RESTRICT,
  target_qty    INTEGER NOT NULL CHECK (target_qty > 0),
  sequence      INTEGER NOT NULL DEFAULT 1 CHECK (sequence > 0),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT work_order_items_unique UNIQUE (work_order_id, item_id)
);

CREATE INDEX IF NOT EXISTS work_order_items_work_order_id_idx ON work_order_items (work_order_id);
CREATE INDEX IF NOT EXISTS work_order_items_item_id_idx ON work_order_items (item_id);

-- =============================================================================
--  MODULE 2 : PRODUCTION (operator playground -> MQTT -> backend)
-- =============================================================================

-- -----------------------------------------------------------------------------
--  downtime_logs — one interval per BREAK / ABNORMALITY / SETUP action.
--  end_time IS NULL means the machine is currently down.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS downtime_logs (
  id                UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  machine_id        UUID NOT NULL REFERENCES machines (id) ON DELETE RESTRICT,
  work_order_id     UUID REFERENCES work_orders (id) ON DELETE SET NULL,
  abnormality_id    UUID REFERENCES abnormalities (id) ON DELETE SET NULL,
  shift_id          UUID REFERENCES shifts (id) ON DELETE SET NULL,
  user_id           UUID REFERENCES users (id) ON DELETE SET NULL,
  reason_type       TEXT NOT NULL CHECK (reason_type IN ('BREAK', 'ABNORMALITY', 'SETUP', 'PLANNED', 'OTHER')),
  category          TEXT,
  start_time        TIMESTAMPTZ NOT NULL,
  end_time          TIMESTAMPTZ,
  duration_seconds  INTEGER CHECK (duration_seconds >= 0),
  remarks           TEXT,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT downtime_logs_window_valid CHECK (end_time IS NULL OR end_time >= start_time),
  -- A BREAK row must not reference an abnormality and vice versa.
  CONSTRAINT downtime_logs_reason_fk CHECK (
    (reason_type = 'ABNORMALITY' AND abnormality_id IS NOT NULL)
    OR (reason_type <> 'ABNORMALITY' AND abnormality_id IS NULL)
  )
);

CREATE INDEX IF NOT EXISTS downtime_logs_machine_start_idx ON downtime_logs (machine_id, start_time DESC);
CREATE INDEX IF NOT EXISTS downtime_logs_reason_start_idx ON downtime_logs (reason_type, start_time DESC);
CREATE INDEX IF NOT EXISTS downtime_logs_work_order_idx ON downtime_logs (work_order_id);
CREATE INDEX IF NOT EXISTS downtime_logs_open_idx ON downtime_logs (machine_id) WHERE end_time IS NULL;

-- -----------------------------------------------------------------------------
--  production_logs — immutable event stream. One row per operator action.
--    START_SHIFT / FINISH_SHIFT -> lifecycle
--    PRODUCE                    -> result = 'OK',  quantity = 1
--    NG                         -> result = 'NG',  quantity = 1, defect_id set
--    BREAK / ABNORMALITY / SETUP-> result NULL,     downtime_log_id set
--  `source` records whether the event came from the playground UI, an MQTT
--  message or a direct REST call.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS production_logs (
  id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  event_type         TEXT NOT NULL
                     CHECK (event_type IN ('START_SHIFT', 'PRODUCE', 'NG', 'SETUP', 'BREAK', 'ABNORMALITY', 'FINISH_SHIFT')),
  result             TEXT CHECK (result IN ('OK', 'NG')),
  quantity           INTEGER NOT NULL DEFAULT 0 CHECK (quantity >= 0),
  machine_id         UUID NOT NULL REFERENCES machines (id) ON DELETE RESTRICT,
  work_order_id      UUID NOT NULL REFERENCES work_orders (id) ON DELETE RESTRICT,
  item_id            UUID NOT NULL REFERENCES items (id) ON DELETE RESTRICT,
  shift_id           UUID NOT NULL REFERENCES shifts (id) ON DELETE RESTRICT,
  user_id            UUID NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  defect_id          UUID REFERENCES defects (id) ON DELETE RESTRICT,
  cycle_time_seconds NUMERIC(10, 3) CHECK (cycle_time_seconds > 0),
  downtime_log_id    UUID REFERENCES downtime_logs (id) ON DELETE SET NULL,
  source             TEXT NOT NULL DEFAULT 'OPERATOR'
                     CHECK (source IN ('OPERATOR', 'MQTT', 'API')),
  remarks            TEXT,
  occurred_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- An NG shot must carry a defect, an OK shot must not.
  CONSTRAINT production_logs_result_defect CHECK (
    (event_type = 'NG' AND result = 'NG' AND defect_id IS NOT NULL)
    OR (event_type = 'PRODUCE' AND result = 'OK' AND defect_id IS NULL)
    OR (event_type NOT IN ('PRODUCE', 'NG') AND result IS NULL)
  ),
  CONSTRAINT production_logs_shot_quantity CHECK (
    event_type NOT IN ('PRODUCE', 'NG') OR quantity = 1
  ),
  CONSTRAINT production_logs_downtime_link CHECK (
    event_type NOT IN ('BREAK', 'ABNORMALITY', 'SETUP') OR downtime_log_id IS NOT NULL
  )
);

-- Analytics/OEE always scan shots and events inside a date range.
CREATE INDEX IF NOT EXISTS production_logs_occurred_at_idx ON production_logs (occurred_at DESC);
CREATE INDEX IF NOT EXISTS production_logs_machine_occurred_idx ON production_logs (machine_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS production_logs_work_order_idx ON production_logs (work_order_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS production_logs_shift_idx ON production_logs (shift_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS production_logs_item_idx ON production_logs (item_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS production_logs_defect_idx ON production_logs (defect_id) WHERE defect_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS production_logs_shots_idx ON production_logs (occurred_at DESC)
  WHERE event_type IN ('PRODUCE', 'NG');
CREATE UNIQUE INDEX IF NOT EXISTS production_logs_cycle_downtime_idx
  ON production_logs (downtime_log_id) WHERE downtime_log_id IS NOT NULL;

-- =============================================================================
--  MODULE 3 : OEE
-- =============================================================================

-- -----------------------------------------------------------------------------
--  oee_records — materialised OEE per machine (and/or per shift / per day).
--  Every input is persisted so a published OEE number can always be traced back
--  to the production logs / downtime logs / defects that produced it:
--
--    availability = run_seconds / planned_seconds
--    performance  = (total_output * ideal_cycle_time_seconds) / run_seconds
--    quality      = ok_count / total_output
--    oee          = availability * performance * quality
--
--  All ratios are stored in the 0..1 range.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS oee_records (
  id                      UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  granularity             TEXT NOT NULL CHECK (granularity IN ('SHIFT', 'DAY')),
  period_date             DATE NOT NULL,
  machine_id              UUID REFERENCES machines (id) ON DELETE CASCADE,
  work_order_id           UUID REFERENCES work_orders (id) ON DELETE SET NULL,
  item_id                 UUID REFERENCES items (id) ON DELETE SET NULL,
  shift_id                UUID REFERENCES shifts (id) ON DELETE SET NULL,
  planned_seconds         INTEGER NOT NULL DEFAULT 0 CHECK (planned_seconds >= 0),
  downtime_seconds        INTEGER NOT NULL DEFAULT 0 CHECK (downtime_seconds >= 0),
  breakdown_seconds       INTEGER NOT NULL DEFAULT 0 CHECK (breakdown_seconds >= 0),
  changeover_seconds      INTEGER NOT NULL DEFAULT 0 CHECK (changeover_seconds >= 0),
  break_seconds           INTEGER NOT NULL DEFAULT 0 CHECK (break_seconds >= 0),
  run_seconds             INTEGER NOT NULL DEFAULT 0 CHECK (run_seconds >= 0),
  ideal_cycle_time_seconds NUMERIC(10, 3),
  ideal_output            NUMERIC(14, 3),
  total_output            INTEGER NOT NULL DEFAULT 0 CHECK (total_output >= 0),
  ok_count                INTEGER NOT NULL DEFAULT 0 CHECK (ok_count >= 0),
  ng_count                INTEGER NOT NULL DEFAULT 0 CHECK (ng_count >= 0),
  availability            NUMERIC(7, 4) NOT NULL DEFAULT 0 CHECK (availability >= 0 AND availability <= 1),
  performance             NUMERIC(7, 4) NOT NULL DEFAULT 0 CHECK (performance >= 0 AND performance <= 1),
  quality                 NUMERIC(7, 4) NOT NULL DEFAULT 0 CHECK (quality >= 0 AND quality <= 1),
  oee                     NUMERIC(7, 4) NOT NULL DEFAULT 0 CHECK (oee >= 0 AND oee <= 1),
  -- per reason downtime seconds, e.g. {"ABNORMALITY": 420, "BREAK": 60}
  breakdown               JSONB NOT NULL DEFAULT '{}'::jsonb,
  computed_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT oee_records_counts_consistent CHECK (ok_count + ng_count = total_output),
  CONSTRAINT oee_records_output_within_run CHECK (
    total_output = 0 OR (ideal_cycle_time_seconds IS NOT NULL AND ideal_cycle_time_seconds > 0)
  )
);

-- NULLs are distinct in a plain UNIQUE constraint, so the uniqueness of
-- (granularity, machine, shift, date) is enforced with an expression index.
CREATE UNIQUE INDEX IF NOT EXISTS oee_records_scope_unique
  ON oee_records (
    granularity,
    COALESCE(machine_id, '00000000-0000-0000-0000-000000000000'::uuid),
    COALESCE(shift_id, '00000000-0000-0000-0000-000000000000'::uuid),
    period_date
  );
CREATE INDEX IF NOT EXISTS oee_records_period_idx ON oee_records (period_date DESC);
CREATE INDEX IF NOT EXISTS oee_records_machine_period_idx ON oee_records (machine_id, period_date DESC);
CREATE INDEX IF NOT EXISTS oee_records_shift_period_idx ON oee_records (shift_id, period_date DESC);

-- =============================================================================
--  updated_at triggers
-- =============================================================================
DO $$
DECLARE
  target TEXT;
BEGIN
  FOREACH target IN ARRAY ARRAY[
    'roles', 'users', 'shifts', 'items', 'machines', 'abnormalities', 'defects',
    'production_setups', 'work_orders', 'work_order_items', 'downtime_logs',
    'oee_records'
  ]
  LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS %I ON %I', target || '_set_updated_at', target);
    EXECUTE format(
      'CREATE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION set_updated_at()',
      target || '_set_updated_at',
      target
    );
  END LOOP;
END $$;

COMMIT;